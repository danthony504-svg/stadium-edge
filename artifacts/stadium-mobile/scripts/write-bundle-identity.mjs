#!/usr/bin/env node
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function sh(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

const branch = sh("git branch --show-current");
const commit = sh("git rev-parse --short HEAD");
const builtAt = new Date().toISOString();

const out = `/** Auto-generated by scripts/write-bundle-identity.mjs — do not edit. */
export const BUNDLE_IDENTITY = {
  branch: ${JSON.stringify(branch)},
  commit: ${JSON.stringify(commit)},
  builtAt: ${JSON.stringify(builtAt)},
} as const;
`;

writeFileSync(join(root, "lib/bundleIdentity.ts"), out, "utf8");
console.log(`bundle identity: ${branch} @ ${commit} (${builtAt})`);
